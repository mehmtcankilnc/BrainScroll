-- BrainScroll daily puzzle, phase 6.
--
-- The point of this file: the daily answer exists ONLY in the database. The app never receives it, so nobody can
-- read it out of the app, the network traffic or the repository. The player sends a guess, the database compares it
-- with the answer, and sends back only the colors. The time is measured by the database clock, not the phone's.
--
-- Everything below is reachable only through three functions (start, state, guess). The tables have Row Level
-- Security on and no policy at all, and no privileges for app users, so there is no other way in.

-- ---------------------------------------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------------------------------------

-- The words a daily puzzle can be. The same words as the app's endless feed, so this list is not secret.
create table public.answer_pool (
    language text not null check (language in ('EN', 'TR')),
    word     text not null check (char_length(word) = 5),
    primary key (language, word)
);

-- Which word is on which day. Filled by the database, at random, when the first player of a day asks.
-- Never filled from this repository, so the schedule is secret.
create table public.daily_puzzle (
    day_index integer not null,
    language  text    not null check (language in ('EN', 'TR')),
    answer    text    not null,
    primary key (day_index, language)
);

-- One player's attempt at one day's puzzle in one language.
create table public.daily_session (
    user_id     uuid    not null references auth.users (id) on delete cascade,
    day_index   integer not null,
    language    text    not null check (language in ('EN', 'TR')),
    -- The clock starts when the player presses Start, measured by the database.
    started_at  timestamptz not null default now(),
    guesses     text[]  not null default '{}',
    feedback    text[]  not null default '{}',  -- one string per guess: C correct, P present, A absent
    finished_at timestamptz,
    outcome     text check (outcome in ('WON', 'LOST')),
    result_id   text,
    primary key (user_id, day_index, language)
);

alter table public.answer_pool   enable row level security;
alter table public.daily_puzzle  enable row level security;
alter table public.daily_session enable row level security;
-- No policies on purpose: app users can neither read nor write these tables. Only the functions below can.
revoke all on public.answer_pool, public.daily_puzzle, public.daily_session from anon, authenticated;

-- Daily results are stored in game_result next to the endless ones, with the time added.
alter table public.game_result
    add column duration_ms bigint check (duration_ms is null or duration_ms >= 0);

-- ---------------------------------------------------------------------------------------------------------
-- Helpers (not callable by app users)
-- ---------------------------------------------------------------------------------------------------------

-- The Istanbul day (days since 1970-01-01 in UTC+3, no daylight saving) of a moment. Same rule as the app's
-- IstanbulDay, so streaks and the daily boundary agree everywhere.
create function public.istanbul_day(p_at timestamptz)
    returns integer
    language sql
    immutable
    set search_path = ''
as $$
    select floor((extract(epoch from p_at) * 1000 + 3 * 3600 * 1000) / 86400000)::integer
$$;

-- Uppercases with the language's own rules. Written out letter by letter so it does not depend on the
-- database's locale: Turkish i becomes İ and ı becomes I, exactly like the app.
create function public.daily_normalize(p_language text, p_text text)
    returns text
    language sql
    immutable
    set search_path = ''
as $$
    select case p_language
        when 'TR' then translate(p_text, 'abcçdefgğhıijklmnoöprsştuüvyz', 'ABCÇDEFGĞHIİJKLMNOÖPRSŞTUÜVYZ')
        else translate(p_text, 'abcdefghijklmnopqrstuvwxyz', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ')
    end
$$;

-- The same two-pass rule as the app's evaluateGuess, so repeated letters are colored identically:
-- 1. exact matches are Correct and removed from the pool of unmatched answer letters;
-- 2. other letters are Present while the pool still has that letter, each hit using one up.
-- Returns one character per letter: C correct, P present, A absent.
create function public.daily_feedback(p_guess text, p_answer text)
    returns text
    language plpgsql
    immutable
    set search_path = ''
as $$
declare
    g      text[] := string_to_array(p_guess, null);
    a      text[] := string_to_array(p_answer, null);
    n      integer := coalesce(array_length(a, 1), 0);
    result text[] := array_fill('A'::text, array[n]);
    pool   jsonb := '{}'::jsonb;
    left_  integer;
begin
    if coalesce(array_length(g, 1), 0) <> n then
        raise exception 'guess and answer must have the same length';
    end if;
    for i in 1..n loop
        if g[i] = a[i] then
            result[i] := 'C';
        else
            pool := jsonb_set(pool, array[a[i]], to_jsonb(coalesce((pool ->> a[i])::integer, 0) + 1));
        end if;
    end loop;
    for i in 1..n loop
        if result[i] <> 'C' then
            left_ := coalesce((pool ->> g[i])::integer, 0);
            if left_ > 0 then
                result[i] := 'P';
                pool := jsonb_set(pool, array[g[i]], to_jsonb(left_ - 1));
            end if;
        end if;
    end loop;
    return array_to_string(result, '');
end;
$$;

-- Makes sure the puzzle of a day exists, choosing a word at random that was not used before in that language
-- (when every word has been used, the cycle starts again). If two players ask at the same moment, the first
-- insert wins and both read the same word.
create function public.ensure_daily_puzzle(p_day integer, p_language text)
    returns text
    language plpgsql
    security definer
    set search_path = ''
as $$
declare
    chosen text;
begin
    select answer into chosen from public.daily_puzzle where day_index = p_day and language = p_language;
    if chosen is not null then
        return chosen;
    end if;

    select word into chosen
    from public.answer_pool p
    where p.language = p_language
      and not exists (select 1 from public.daily_puzzle d where d.language = p_language and d.answer = p.word)
    order by random()
    limit 1;

    if chosen is null then -- the pool is used up: start a new cycle
        select word into chosen from public.answer_pool where language = p_language order by random() limit 1;
    end if;
    if chosen is null then
        raise exception 'no answers for language %', p_language using errcode = 'P0002';
    end if;

    insert into public.daily_puzzle (day_index, language, answer) values (p_day, p_language, chosen)
    on conflict do nothing;

    select answer into chosen from public.daily_puzzle where day_index = p_day and language = p_language;
    return chosen;
end;
$$;

-- What the app is told about an attempt. The answer is included only once the attempt is over.
create function public.daily_state_json(s public.daily_session, p_answer text)
    returns jsonb
    language sql
    stable
    set search_path = ''
as $$
    select jsonb_build_object(
        'day_index', s.day_index,
        'language', s.language,
        'status', case when s.outcome is null then 'PLAYING' else s.outcome end,
        'max_attempts', 6,
        'guesses', coalesce((
            select jsonb_agg(jsonb_build_object('word', t.word, 'feedback', t.feedback) order by t.n)
            from unnest(s.guesses, s.feedback) with ordinality as t(word, feedback, n)
        ), '[]'::jsonb),
        'started_at_ms', floor(extract(epoch from s.started_at) * 1000)::bigint,
        'finished_at_ms', case when s.finished_at is null then null
                          else floor(extract(epoch from s.finished_at) * 1000)::bigint end,
        'duration_ms', case when s.finished_at is null then null
                       else floor(extract(epoch from (s.finished_at - s.started_at)) * 1000)::bigint end,
        'answer', case when s.outcome is null then null else p_answer end,
        'result_id', s.result_id,
        'server_now_ms', floor(extract(epoch from now()) * 1000)::bigint
    )
$$;

-- ---------------------------------------------------------------------------------------------------------
-- The three functions the app can call
-- ---------------------------------------------------------------------------------------------------------

-- Starts today's puzzle (and the clock). Asking again while it is running or finished changes nothing and just
-- returns the current state, so reinstalling the app or switching phones cannot restart the clock.
create function public.start_daily(p_language text)
    returns jsonb
    language plpgsql
    security definer
    set search_path = ''
as $$
declare
    uid     uuid := auth.uid();
    today   integer := public.istanbul_day(now());
    ans     text;
    sess public.daily_session;
begin
    if uid is null then
        raise exception 'not signed in' using errcode = '28000';
    end if;
    if p_language not in ('EN', 'TR') then
        raise exception 'unknown language' using errcode = '22023';
    end if;

    ans := public.ensure_daily_puzzle(today, p_language);

    insert into public.daily_session (user_id, day_index, language)
    values (uid, today, p_language)
    on conflict do nothing;

    select * into sess from public.daily_session
    where user_id = uid and day_index = today and language = p_language;
    return public.daily_state_json(sess, ans);
end;
$$;

-- Today's attempt without starting it: the app uses this to show "Start", "Continue" or the result.
create function public.get_daily_state(p_language text)
    returns jsonb
    language plpgsql
    security definer
    set search_path = ''
as $$
declare
    uid     uuid := auth.uid();
    today   integer := public.istanbul_day(now());
    sess public.daily_session;
begin
    if uid is null then
        raise exception 'not signed in' using errcode = '28000';
    end if;
    if p_language not in ('EN', 'TR') then
        raise exception 'unknown language' using errcode = '22023';
    end if;

    select * into sess from public.daily_session
    where user_id = uid and day_index = today and language = p_language;
    if not found then
        return jsonb_build_object(
            'day_index', today, 'language', p_language, 'status', 'NOT_STARTED', 'max_attempts', 6,
            'guesses', '[]'::jsonb, 'started_at_ms', null, 'finished_at_ms', null, 'duration_ms', null, 'answer', null, 'result_id', null,
            'server_now_ms', floor(extract(epoch from now()) * 1000)::bigint);
    end if;
    return public.daily_state_json(
        sess,
        (select answer from public.daily_puzzle where day_index = today and language = p_language));
end;
$$;

-- One guess. The database colors it, stores it, and, if that ends the attempt, measures the time and records
-- the result. Which attempt: the player's unfinished one for that language (usually today's; one started just
-- before midnight can still be finished after it).
create function public.submit_daily_guess(p_language text, p_guess text)
    returns jsonb
    language plpgsql
    security definer
    set search_path = ''
as $$
declare
    uid      uuid := auth.uid();
    guess    text;
    sess  public.daily_session;
    ans      text;
    fb       text;
    done     boolean;
    outcome_ text;
    pattern  text;
begin
    if uid is null then
        raise exception 'not signed in' using errcode = '28000';
    end if;
    if p_language not in ('EN', 'TR') then
        raise exception 'unknown language' using errcode = '22023';
    end if;

    guess := public.daily_normalize(p_language, coalesce(p_guess, ''));
    pattern := case p_language
        when 'TR' then '^[ABCÇDEFGĞHIİJKLMNOÖPRSŞTUÜVYZ]{5}$'
        else '^[ABCDEFGHIJKLMNOPQRSTUVWXYZ]{5}$'
    end;
    if guess !~ pattern then
        raise exception 'invalid guess' using errcode = '22023';
    end if;

    -- Lock the row: two phones guessing at the same time are handled one after the other.
    select * into sess from public.daily_session
    where user_id = uid and language = p_language and finished_at is null
    order by day_index desc
    limit 1
    for update;
    if not found then
        -- Either never started, or already finished: tell them apart for a clear message.
        if exists (select 1 from public.daily_session
                   where user_id = uid and language = p_language and day_index = public.istanbul_day(now())) then
            raise exception 'already finished' using errcode = 'P0003';
        end if;
        raise exception 'not started' using errcode = 'P0004';
    end if;

    select answer into ans from public.daily_puzzle where day_index = sess.day_index and language = p_language;
    fb := public.daily_feedback(guess, ans);
    done := (guess = ans) or (coalesce(array_length(sess.guesses, 1), 0) + 1 >= 6);
    outcome_ := case when not done then null when guess = ans then 'WON' else 'LOST' end;

    update public.daily_session set
        guesses = guesses || guess,
        feedback = feedback || fb,
        finished_at = case when done then now() end,
        outcome = outcome_,
        result_id = case when done then gen_random_uuid()::text end
    where user_id = uid and day_index = sess.day_index and language = p_language
    returning * into sess;

    if done then
        -- The result is written here, by the database, with the database's clock. Clients cannot write daily
        -- results themselves (the policy on game_result only allows endless ones).
        insert into public.game_result
            (user_id, id, game, mode, language, answer, guesses, outcome, was_skipped, finished_at, day_index, duration_ms)
        values
            (uid, sess.result_id, 'word', 'DAILY', p_language, ans, array_to_string(sess.guesses, ','),
             outcome_, false, floor(extract(epoch from sess.finished_at) * 1000)::bigint, sess.day_index,
             floor(extract(epoch from (sess.finished_at - sess.started_at)) * 1000)::bigint);
    end if;

    return public.daily_state_json(sess, ans);
end;
$$;

-- ---------------------------------------------------------------------------------------------------------
-- Who may call what
-- ---------------------------------------------------------------------------------------------------------
-- Functions are callable by everyone by default, so first take that away, then give back exactly three.
-- Anonymous app users are "authenticated" users too, so they can play the daily puzzle.
revoke all on function
    public.istanbul_day(timestamptz),
    public.daily_normalize(text, text),
    public.daily_feedback(text, text),
    public.ensure_daily_puzzle(integer, text),
    public.daily_state_json(public.daily_session, text),
    public.start_daily(text),
    public.get_daily_state(text),
    public.submit_daily_guess(text, text)
from public, anon, authenticated;

grant execute on function
    public.start_daily(text),
    public.get_daily_state(text),
    public.submit_daily_guess(text, text)
to authenticated;

